import fs from 'node:fs/promises';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {rolldown} from 'rolldown';
await import('./build-local.mjs');
await fs.mkdir('cloud/generated',{recursive:true});
let market=await fs.readFile('standalone/generated/market.mjs','utf8');
market=market.replace(/^import \{ env \} from .*;\r?\n/m,'').replace(/^import \{ getChatGPTUser \} from .*;\r?\n/m,'').replaceAll('GET(req)', 'GET(req, env, authUser)').replaceAll('POST(req)', 'POST(req, env, authUser)').replaceAll('await getChatGPTUser()', 'authUser');
await fs.writeFile('cloud/generated/market.mjs',market);
await fs.copyFile('standalone/generated/domain.mjs','cloud/generated/domain.mjs');
await fs.mkdir('dist/pages',{recursive:true});
await fs.cp('standalone/public','dist/pages',{recursive:true});
const bundle=await rolldown({input:'cloud/entry.mjs',platform:'browser'});
await bundle.write({file:'dist/pages/_worker.js',format:'esm',minify:true}); await bundle.close();
await fs.writeFile('dist/pages/_routes.json',JSON.stringify({version:1,include:['/api/*','/auth/*','/signup','/signin-with-chatgpt','/signout-with-chatgpt'],exclude:[]}));
const archive=path.resolve('../gaon-bazaar-cloudflare.zip');
const packed=spawnSync('tar',['-a','-cf',archive,'-C','dist/pages','.'],{stdio:'inherit',windowsHide:true});
if(packed.status!==0)throw Error('Packaging failed');
const schema=await fs.readFile('drizzle/0000_marketplace.sql','utf8')+'\n'+await fs.readFile('cloud/auth-schema.sql','utf8');
await fs.writeFile('cloud/setup.sql',schema.replaceAll('--> statement-breakpoint',''));
console.log('Cloudflare Pages release:',archive);
